/**
 * Desenha um ícone. x/y em mm (canto superior esquerdo da caixa do ícone),
 * `size` = lado da caixa em mm. `peso` é a espessura no espaço 24×24 do ícone,
 * então a aparência fica constante em qualquer tamanho.
 */
export function icon(page, nome, { x, y, size = 5, color = COR.navy, peso = 1.7 }) {
  const paths = ICONS[nome] ?? ICONS.dot;
  const scale = W(size) / 24;
  for (const d of paths) {
    page.drawSvgPath(d, { x: X(x), y: Y(y), scale, borderColor: color, borderWidth: peso, lineCap: 1, lineJoin: 1 });
  }
}

/** Ícone dentro de um selo arredondado (usado nas linhas de card e na grade de inclusos). */
export function iconBadge(page, nome, { x, y, box = 9, size = 5.2, fundo, borda, color = COR.navy, peso = 1.7, raio = 2.4 }) {
  if (fundo || borda) {
    page.drawSvgPath(
      `M ${W(raio)} 0 H ${W(box) - W(raio)} A ${W(raio)} ${W(raio)} 0 0 1 ${W(box)} ${W(raio)} `
      + `V ${W(box) - W(raio)} A ${W(raio)} ${W(raio)} 0 0 1 ${W(box) - W(raio)} ${W(box)} `
      + `H ${W(raio)} A ${W(raio)} ${W(raio)} 0 0 1 0 ${W(box) - W(raio)} V ${W(raio)} `
      + `A ${W(raio)} ${W(raio)} 0 0 1 ${W(raio)} 0 Z`,
      { x: X(x), y: Y(y), ...(fundo ? { color: fundo } : {}), ...(borda ? { borderColor: borda, borderWidth: 0.6 } : {}) },
    );
  }
  icon(page, nome, { x: x + (box - size) / 2, y: y + (box - size) / 2, size, color, peso });
}
